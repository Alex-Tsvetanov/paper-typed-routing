#!/usr/bin/env python3
"""The ablations of RegexMatcher v2's design choices (design/review-runs/ablations.md; exploratory, decides
nothing): one run of bench/jobs/review-grid.sh to a summary and macros.

    ablations.py RUN_DIR [--code-size FILE] [--verified FILE] [--out summary.json] [--macros FILE.tex]
                 [--csv FILE] [--resamples 10000] [--seed SEED]

RUN_DIR holds run_grid.sh's cells.jsonl (the job's grid/ directory); --verified is run_grid.sh's
verified.jsonl (default: RUN_DIR/verified.jsonl when it exists); --code-size is the job's code-size.tsv.

The statistic, fixed in the plan: per cell of the 35 (the seven shapes at m = 10 to 100,000) and per
variant (ab-linear, ab-hashed, ab-noexact, ab-bytes), the ratio of the variant's lookup time (ns_median) to
the copy's, and to the pinned arm's: the median over the seed pairs of the per-pair ratio, with the 95% BCa
interval over the pairs (analysis/review_common.py, as analysis/h1_stats.py computes H1's). The copy's
ratio to the pinned arm is reported the same way, as the control. Beside them, per arm and cell, as the
earlier campaign's work-per-lookup analysis computes them (analysis/h2_stats.py): the instructions per
lookup net of the null arm of the same pair (the median over the processes), the branch misses per lookup
(raw, the median over the processes), and the median time per lookup; and per arm its normalized lookup
code size (code-size.tsv: the lines of bench/objdump_check.sh's normalized disassembly of the arm's lookup,
at the flags the arms are compiled with).

An arm takes part in a cell only if every one of its processes is usable (analysis/cells.py) and its
processes are exactly the design's sixteen seed pairs; otherwise the arm is listed as absent or failing with
the reason, and every process that is not usable is listed. A ratio is computed over all sixteen pairs only
(the pairs two arms share are never used instead), and every comparison carries the number of pairs it is
over ("pairs"; 0 where it was not made). Nothing is dropped in silence, no comparison is tested, and no
multiplicity adjustment is made.

Macros (letters only, prefixed Abl): per variant and reference, \\Abl<Variant>Vs<Ref><Cell>Ratio, ...Low
and ...High (Variant: Copy (against the pinned arm only), Linear, Hashed, Noexact, Bytes; Ref: Copy, Vtwo;
Cell: for example StaticTen), with each one's smallest and largest ratio over the cells
(\\Abl<Variant>Vs<Ref>RatioMin, ...Max) and the cells compared (...Cells); per arm and cell
\\Abl<Arm><Cell>NetInstructions and ...BranchMisses; per arm \\Abl<Arm>CodeLines.
"""

from __future__ import annotations

import argparse
import csv
import json
import sys
from pathlib import Path

import numpy as np

sys.path.insert(0, str(Path(__file__).resolve().parent))
from cells import H1_SHAPES, H1_SIZES, load  # noqa: E402
from h2_stats import net, nulls_of  # noqa: E402
from macros_util import Macros, cell_word, count, instructions, nanoseconds, per_lookup, ratio  # noqa: E402
from review_common import ARM_WORD, RESAMPLES, SEED, median_of, not_compared, ratio_ci, sort_arms, values  # noqa: E402

PINNED = "regexmatcher-v2"
COPY = "regexmatcher-v2-copy"
VARIANTS = ("regexmatcher-v2-ab-linear", "regexmatcher-v2-ab-hashed", "regexmatcher-v2-ab-noexact",
            "regexmatcher-v2-ab-bytes")
NULL = "null"
ARMS = (PINNED, COPY) + VARIANTS + (NULL,)
LOOKUP_ARMS = (PINNED, COPY) + VARIANTS
# (numerator, reference) in the order of the resamples: the control, then each variant against the copy
# and against the pinned arm.
COMPARISONS = ((COPY, PINNED),) + tuple((v, r) for v in VARIANTS for r in (COPY, PINNED))
HEAD = ("% Generated by analysis/ablations.py from a run of bench/jobs/review-grid.sh "
        "(design/review-runs/ablations.md; exploratory). Do not edit.\n")


def read_code_size(path: Path | None) -> dict[str, int]:
    """code-size.tsv: arm, normalized lines (and more columns, which are kept in the job's output)."""
    if path is None or not path.exists():
        return {}
    with path.open(encoding="utf-8") as f:
        return {r["arm"]: int(r["lines"]) for r in csv.DictReader(f, delimiter="\t") if r.get("lines")}


def summarize(cells: dict, code: dict[str, int], resamples: int = RESAMPLES, seed: int = SEED,
              keys: list[tuple] | None = None) -> dict:
    keys = keys if keys is not None else [(s, m) for s in H1_SHAPES for m in H1_SIZES]
    rng = np.random.default_rng(seed)
    rows = []
    for shape, m in keys:
        cell = cells.get((shape, m), {})
        arms = sort_arms(cell, shape, list(ARMS))
        nulls = nulls_of(cell)
        row: dict = {"shape": shape, "m": m, "absent": arms.absent, "failing": arms.failing,
                     "unusable": arms.unusable, "arms": {}, "comparisons": []}
        for a in LOOKUP_ARMS:
            if a in arms.ok:
                rs = arms.ok[a]
                row["arms"][a] = {"ns": median_of(rs, "ns_median"),
                                  "net_instructions": median_of(rs, lambda r: net(r, nulls)),
                                  "branch_misses": median_of(rs, "branch_misses"),
                                  "instructions": median_of(rs, "instructions"), "processes": len(rs)}
        for num, ref in COMPARISONS:
            c = {"arm": num, "reference": ref}
            if num in arms.ok and ref in arms.ok:
                c.update(ratio_ci(values(arms.ok[num], "ns_median"), {ref: values(arms.ok[ref], "ns_median")},
                                  rng, resamples))
            else:
                c.update(not_compared("; ".join(
                    f"{a}: {arms.absent.get(a) or arms.failing.get(a)}" for a in (num, ref) if a not in arms.ok)))
            row["comparisons"].append(c)
        rows.append(row)
    totals = {}
    for num, ref in COMPARISONS:
        done = [c for r in rows for c in r["comparisons"]
                if c["arm"] == num and c["reference"] == ref and c["status"] == "compared"]
        totals[f"{num} / {ref}"] = {"cells": len(done),
                                    "ratio_min": min((c["ratio"] for c in done), default=None),
                                    "ratio_max": max((c["ratio"] for c in done), default=None)}
    return {"cells": rows, "totals": totals, "code_lines": {a: code.get(a) for a in LOOKUP_ARMS},
            "resamples": resamples, "seed": seed}


def macros(s: dict) -> str:
    mc = Macros()
    word = dict(ARM_WORD)
    for r in s["cells"]:
        cw = cell_word(r["shape"], r["m"])
        for c in r["comparisons"]:
            if c["status"] != "compared":
                continue
            name = f"Abl{word[c['arm']]}Vs{word[c['reference']]}{cw}"
            mc.add(name + "Ratio", ratio(c["ratio"]))
            mc.add(name + "Low", ratio(c["low"]))
            mc.add(name + "High", ratio(c["high"]))
        for a, v in r["arms"].items():
            if v["net_instructions"] is not None:
                mc.add(f"Abl{word[a]}{cw}NetInstructions", instructions(v["net_instructions"]))
            if v["branch_misses"] is not None:
                mc.add(f"Abl{word[a]}{cw}BranchMisses", per_lookup(v["branch_misses"]))
            if v["ns"] is not None:
                mc.add(f"Abl{word[a]}{cw}Ns", nanoseconds(v["ns"]))
    for key, t in s["totals"].items():
        num, ref = key.split(" / ")
        name = f"Abl{word[num]}Vs{word[ref]}"
        mc.add(name + "Cells", count(t["cells"]))
        if t["ratio_min"] is not None:
            mc.add(name + "RatioMin", ratio(t["ratio_min"]))
            mc.add(name + "RatioMax", ratio(t["ratio_max"]))
    for a, lines in s["code_lines"].items():
        if lines is not None:
            mc.add(f"Abl{word[a]}CodeLines", count(lines))
    return HEAD + mc.text()


def report(s: dict) -> None:
    for r in s["cells"]:
        head = f"{r['shape']:<14} {r['m']:>7}"
        for c in r["comparisons"]:
            label = f"{c['arm'].removeprefix('regexmatcher-v2-')} / {c['reference'].removeprefix('regexmatcher-')}"
            if c["status"] == "compared":
                print(f"{head}  {label:<20} {c['ratio']:.4f} [{c['low']:.4f}, {c['high']:.4f}] ({c['pairs']} pairs)")
            else:
                print(f"{head}  {label:<20} {c['status']}: {c.get('why', '')}")
        for u in r["unusable"]:
            print(f"{head}  not usable: {u}")
    for key, t in s["totals"].items():
        print(f"{key}: {t['cells']} cells compared, ratio {t['ratio_min']} to {t['ratio_max']}")
    print(f"code lines: {s['code_lines']}")


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("run", type=Path)
    ap.add_argument("--code-size", type=Path)
    ap.add_argument("--verified", type=Path)
    ap.add_argument("--out", type=Path)
    ap.add_argument("--macros", type=Path)
    ap.add_argument("--csv", type=Path)
    ap.add_argument("--resamples", type=int, default=RESAMPLES)
    ap.add_argument("--seed", type=int, default=SEED)
    a = ap.parse_args()
    verified = a.verified or (a.run / "verified.jsonl" if (a.run / "verified.jsonl").exists() else None)
    s = summarize(load(a.run, verified), read_code_size(a.code_size), a.resamples, a.seed)
    if a.out:
        a.out.write_text(json.dumps(s, indent=1) + "\n", encoding="utf-8")
    if a.macros:
        a.macros.write_text(macros(s), encoding="utf-8")
    if a.csv:
        fields = ["shape", "m", "arm", "reference", "status", "pairs", "ratio", "low", "high", "min_pair", "max_pair",
                  "why"]
        with a.csv.open("w", newline="", encoding="utf-8") as f:
            w = csv.DictWriter(f, fieldnames=fields, extrasaction="ignore")
            w.writeheader()
            for r in s["cells"]:
                for c in r["comparisons"]:
                    w.writerow({"shape": r["shape"], "m": r["m"], **c})
    report(s)
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
