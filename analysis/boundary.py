#!/usr/bin/env python3
"""The language-boundary arms at small sizes (design/review-runs/boundary-arms.md; exploratory, decides
nothing): one run of bench/jobs/review-grid.sh to a summary and macros.

    boundary.py RUN_DIR [--verified FILE] [--out summary.json] [--macros FILE.tex] [--csv FILE]
                [--resamples 10000] [--seed SEED]

RUN_DIR holds run_grid.sh's cells.jsonl (the job's grid/ directory); --verified is run_grid.sh's
verified.jsonl (default: RUN_DIR/verified.jsonl when it exists). The cells are the seven shapes at m = 10
and m = 100. Every ratio is the median over the seed pairs of the per-pair ratio with the 95% BCa interval
over the pairs (analysis/review_common.py, as analysis/h1_stats.py computes H1's); where a ratio is to
"the fastest" of several arms, the fastest is the one with the lowest median over the pairs, chosen again
in every resample, as in H1. The statistics, fixed in the plan:

1. Symmetric comparison: per cell, regexmatcher-v2-capi's time per lookup (ns_median) over each Rust arm's
   (matchit, actix-router, path-tree) and over the fastest of them.
2. Net of each arm's own null: each process's time per lookup minus its own null's in the same pair:
   regexmatcher-v2 and the C++ competitors (uwebsockets, glaze) minus the C++ null arm of their loop
   (the record's loop_null: null for v2, null-no405 for the C++ competitors, as the earlier campaign
   pairs them); regexmatcher-v2-capi minus capi-null; the Rust arms minus rust-null; the Go arms (gin,
   httprouter, nethttp, chi) and regexmatcher-v2-goloop minus their own null pass in Go (null_ns, measured
   in the same process). Per cell, v2's net time over the fastest competitor's net time (the nine
   competitors above), with the raw times beside. A ratio needs a positive net time: an arm whose net
   time is not positive in some pair (or whose null is not usable in every pair) is listed, per cell, in
   net_left_out and left out of that cell's net comparison; if that arm has the lowest raw median of the
   competitors in the cell, the cell's net ratio is not computed (status "not compared", with the reason).
3. v2 in a Go loop: per cell, regexmatcher-v2-goloop's time per lookup over each Go arm's, labelled as
   including the Go-to-C call (no Go arm makes one per lookup).

An arm takes part in a cell only if every one of its processes is usable (analysis/cells.py) and its
processes are exactly the design's sixteen seed pairs; otherwise the arm is listed as absent (for example gin
on mixed-overlap, whose answers differ as bench/semantics.json declares) or failing, with the reason, and
every process that is not usable is listed. A ratio is computed over all sixteen pairs only (the pairs two
arms share are never used instead), and every comparison carries the number of pairs it is over ("pairs"; 0
where it was not made). Nothing is dropped in silence, no comparison is tested, and no multiplicity
adjustment is made.

Macros (letters only, prefixed Bnd; Cell for example StaticTen): \\BndCapiVs<Rust arm or Fastest><Cell>
Ratio, Low, High; \\BndNet<Cell>Ratio, Low, High and \\BndNet<Cell>Fastest (the arm), with \\BndRaw<Cell>
Ratio, Low, High beside (v2 against the same competitors on raw times); \\BndGoloopVs<Go arm><Cell>Ratio,
Low, High; per arm \\Bnd<Arm><Cell>Ns and, for the arms with a null, ...NetNs; \\BndNetLeftOutCells, the
number of cells where any arm was left out of the net comparison.
"""

from __future__ import annotations

import argparse
import csv
import json
import sys
from pathlib import Path

import numpy as np

sys.path.insert(0, str(Path(__file__).resolve().parent))
from cells import H1_SHAPES, load, pair  # noqa: E402
from macros_util import Macros, cell_word, count, nanoseconds, ratio, tt  # noqa: E402
from review_common import ARM_WORD, RESAMPLES, SEED, median_of, not_compared, ratio_ci, sort_arms, values  # noqa: E402

SIZES = (10, 100)
V2 = "regexmatcher-v2"
CAPI = "regexmatcher-v2-capi"
GOLOOP = "regexmatcher-v2-goloop"
RUST = ("matchit", "actix-router", "path-tree")
GO = ("gin", "httprouter", "nethttp", "chi")
CPP = ("uwebsockets", "glaze")
COMPETITORS = RUST + GO + CPP
NULLS = ("null", "null-no405", "capi-null", "rust-null")
ARMS = (V2, CAPI, GOLOOP) + COMPETITORS + NULLS
# The null each arm's time is taken net of, where it is another arm; the Go arms and goloop use their own
# null pass (null_ns), and v2 and the C++ competitors the null of their loop (the record's loop_null).
OWN_NULL = {CAPI: "capi-null", **{a: "rust-null" for a in RUST}}
HEAD = ("% Generated by analysis/boundary.py from a run of bench/jobs/review-grid.sh "
        "(design/review-runs/boundary-arms.md; exploratory). Do not edit.\n")


def null_of(arm: str, r: dict) -> str | None:
    """The null arm whose time this process is taken net of, or "own" (its own null pass), or None."""
    if arm in OWN_NULL:
        return OWN_NULL[arm]
    loop = r.get("loop_null")
    return loop if loop in ("own", "null", "null-no405") else None


def net_times(arm: str, rows: list[dict], cell: dict[str, list[dict]]) -> dict[tuple, float]:
    """Each process's time per lookup minus its own null's in the same pair (pairs without one left out)."""
    out = {}
    for r in rows:
        which = null_of(arm, r)
        if which == "own":
            base = r.get("null_ns")
        elif which is not None:
            base = values(cell.get(which, []), "ns_median").get(pair(r))
        else:
            base = None
        if isinstance(r.get("ns_median"), (int, float)) and isinstance(base, (int, float)):
            out[pair(r)] = float(r["ns_median"]) - float(base)
    return out


def summarize(cells: dict, resamples: int = RESAMPLES, seed: int = SEED, keys: list[tuple] | None = None) -> dict:
    keys = keys if keys is not None else [(s, m) for s in H1_SHAPES for m in SIZES]
    rng = np.random.default_rng(seed)
    rows = []
    for shape, m in keys:
        cell = cells.get((shape, m), {})
        arms = sort_arms(cell, shape, list(ARMS))
        ok = arms.ok
        row: dict = {"shape": shape, "m": m, "absent": arms.absent, "failing": arms.failing,
                     "unusable": arms.unusable, "arms": {}, "symmetric": [], "net": {}, "goloop": []}
        nets = {}
        for a in ARMS:
            if a not in ok:
                continue
            info = {"ns": median_of(ok[a], "ns_median"), "processes": len(ok[a])}
            if a not in NULLS:
                n = net_times(a, ok[a], {k: v for k, v in ok.items() if k in NULLS})
                if len(n) == len(ok[a]):
                    nets[a] = n
                    info["net_ns"] = float(np.median(list(n.values())))
                else:
                    info["net_note"] = "its null is not usable in every pair"
            row["arms"][a] = info
        # 1. v2 behind a C call against the Rust arms, raw times.
        raw = {a: values(ok[a], "ns_median") for a in ok}
        for target in RUST + ("fastest",):
            dens = {a: raw[a] for a in RUST if a in raw} if target == "fastest" else (
                {target: raw[target]} if target in raw else {})
            c = {"against": target}
            if CAPI in raw and dens:
                c.update(ratio_ci(raw[CAPI], dens, rng, resamples))
            else:
                c.update(not_compared("; ".join(
                    f"{a}: {arms.absent.get(a) or arms.failing.get(a)}" for a in ((CAPI,) + (RUST if target == "fastest"
                                                                                           else (target,)))
                    if a not in raw)))
            row["symmetric"].append(c)
        # 2. Net of each arm's own null: v2 against the fastest competitor.
        positive = {a: n for a, n in nets.items() if all(v > 0 for v in n.values())}
        row["net_not_positive"] = sorted(a for a in nets if a not in positive)
        # Every arm of the comparison that takes part in the cell and is left out of it, with why.
        left_out = {a: ("its net time is not positive in some pair" if a in nets else
                        "its null is not usable in every pair") for a in (V2,) + COMPETITORS
                    if a in ok and a not in positive}
        row["net_left_out"] = left_out
        comp = {a: positive[a] for a in COMPETITORS if a in positive}
        # An arm left out that has the lowest raw median of the competitors would have been the fastest one,
        # or cannot be ranked: the ratio against the fastest of the others would not be the plan's.
        medians = {a: row["arms"][a]["ns"] for a in COMPETITORS if a in ok}
        ranked = {a: v for a, v in medians.items() if v is not None}
        lowest = min(ranked, key=ranked.get) if ranked else None
        unranked_out = sorted(a for a in medians if medians[a] is None and a in left_out)
        if V2 not in positive:
            row["net"] = not_compared("v2's net time is missing or not positive")
        elif not comp:
            row["net"] = not_compared("no competitor's net time")
        elif lowest in left_out or unranked_out:
            who = lowest if lowest in left_out else unranked_out[0]
            row["net"] = not_compared(f"{who} is left out of the net comparison ({left_out[who]}) and "
                                      + ("has the lowest raw median of the competitors" if who == lowest
                                         else "has no raw median to rank it by"))
        else:
            row["net"] = ratio_ci(positive[V2], comp, rng, resamples)
            # Beside it, the same comparison on the raw times (the same competitors).
            row["net"]["raw"] = ratio_ci(raw[V2], {a: raw[a] for a in comp}, rng, resamples)
        # 3. v2 in a Go loop against each Go arm, raw times (including the Go-to-C call).
        for target in GO:
            c = {"against": target}
            if GOLOOP in raw and target in raw:
                c.update(ratio_ci(raw[GOLOOP], {target: raw[target]}, rng, resamples))
            else:
                c.update(not_compared("; ".join(
                    f"{a}: {arms.absent.get(a) or arms.failing.get(a)}" for a in (GOLOOP, target) if a not in raw)))
            row["goloop"].append(c)
        rows.append(row)
    return {"cells": rows, "net_left_out_cells": sum(1 for r in rows if r["net_left_out"]),
            "resamples": resamples, "seed": seed}


def macros(s: dict) -> str:
    mc = Macros()
    for r in s["cells"]:
        cw = cell_word(r["shape"], r["m"])

        def trio(name: str, c: dict) -> None:
            if c.get("status") == "compared":
                mc.add(name + "Ratio", ratio(c["ratio"]))
                mc.add(name + "Low", ratio(c["low"]))
                mc.add(name + "High", ratio(c["high"]))

        for c in r["symmetric"]:
            word = "Fastest" if c["against"] == "fastest" else ARM_WORD[c["against"]]
            trio(f"BndCapiVs{word}{cw}", c)
            if c["against"] == "fastest" and c.get("status") == "compared":
                mc.add(f"BndCapiVsFastest{cw}Arm", tt(c["fastest"]))
        trio(f"BndNet{cw}", r["net"])
        if r["net"].get("status") == "compared":
            mc.add(f"BndNet{cw}Fastest", tt(r["net"]["fastest"]))
            trio(f"BndRaw{cw}", r["net"]["raw"])
        for c in r["goloop"]:
            trio(f"BndGoloopVs{ARM_WORD[c['against']]}{cw}", c)
        for a, v in r["arms"].items():
            if v.get("ns") is not None:
                mc.add(f"Bnd{ARM_WORD[a]}{cw}Ns", nanoseconds(v["ns"]))
            if v.get("net_ns") is not None:
                mc.add(f"Bnd{ARM_WORD[a]}{cw}NetNs", nanoseconds(v["net_ns"]))
    mc.add("BndNetLeftOutCells", count(s["net_left_out_cells"]))
    return HEAD + mc.text()


def report(s: dict) -> None:
    def line(c: dict) -> str:
        if c.get("status") != "compared":
            return f"{c.get('status')}: {c.get('why', '')}"
        return f"{c['ratio']:.4f} [{c['low']:.4f}, {c['high']:.4f}] vs {c['fastest']} ({c['pairs']} pairs)"

    for r in s["cells"]:
        head = f"{r['shape']:<14} {r['m']:>4}"
        for c in r["symmetric"]:
            print(f"{head}  capi / {c['against']:<12} {line(c)}")
        print(f"{head}  v2 net / fastest net  {line(r['net'])}")
        for c in r["goloop"]:
            print(f"{head}  goloop / {c['against']:<10} {line(c)} (with the Go-to-C call)")
        for a, why in r["net_left_out"].items():
            print(f"{head}  left out of the net comparison: {a} ({why})")
        for u in r["unusable"]:
            print(f"{head}  not usable: {u}")


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("run", type=Path)
    ap.add_argument("--verified", type=Path)
    ap.add_argument("--out", type=Path)
    ap.add_argument("--macros", type=Path)
    ap.add_argument("--csv", type=Path)
    ap.add_argument("--resamples", type=int, default=RESAMPLES)
    ap.add_argument("--seed", type=int, default=SEED)
    a = ap.parse_args()
    verified = a.verified or (a.run / "verified.jsonl" if (a.run / "verified.jsonl").exists() else None)
    s = summarize(load(a.run, verified), a.resamples, a.seed)
    if a.out:
        a.out.write_text(json.dumps(s, indent=1) + "\n", encoding="utf-8")
    if a.macros:
        a.macros.write_text(macros(s), encoding="utf-8")
    if a.csv:
        fields = ["shape", "m", "kind", "against", "status", "pairs", "ratio", "low", "high", "fastest", "why"]
        with a.csv.open("w", newline="", encoding="utf-8") as f:
            w = csv.DictWriter(f, fieldnames=fields, extrasaction="ignore")
            w.writeheader()
            for r in s["cells"]:
                for c in r["symmetric"]:
                    w.writerow({"shape": r["shape"], "m": r["m"], "kind": "capi", **c})
                w.writerow({"shape": r["shape"], "m": r["m"], "kind": "net", "against": "fastest", **r["net"]})
                for c in r["goloop"]:
                    w.writerow({"shape": r["shape"], "m": r["m"], "kind": "goloop", **c})
    report(s)
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
