def word(arm: str) -> str:
    """A macro-name word for an arm: letters only."""
    special = {"r3": "RThree", "regexmatcher-v2": "VTwo", "regexmatcher-v1": "VOne", "nethttp": "NetHttp",
               "uwebsockets": "UWebSockets", "cpp-httplib": "CppHttplib", "boost-url": "BoostUrl", "oatpp": "Oatpp"}
    if arm in special:
        return special[arm]
    return "".join(p.capitalize() for p in re.split(r"[^A-Za-z]+", arm) if p)


def arm_tt(arm: str) -> str:
    return tt(arm)


def shape_cell(shape: str, m: int) -> str:
    """The shape column of a table: the name on the first size of a shape only."""
    return f"\\shape{{{shape}}}" if m == SIZES[0] else ""


def yes(b: bool) -> str:
    return "yes" if b else "no"


def sig(x: float, digits: int = 3) -> str:
    """Three significant figures, grouped."""
    if x == 0:
        return "0"
    places = digits - 1 - math.floor(math.log10(abs(x)))
    return fixed(round(x, places), max(0, places))


def math_sci(x: float) -> str:
    return f"${scientific(x)}$"


def fl(v: str) -> float:
    return float(v)


def truth(v: str) -> bool:
    return str(v) == "True"


def check(cond: bool, what: str) -> None:
    if not cond:
        raise SystemExit(f"paper_macros: a fact the paper states is false: {what}")


