def pair_details(mc: Macros, run: Path) -> None:
    """Per-pair facts of two cells the paper discusses, from the main grid's cells.jsonl: H7's lost
    cell (the frozen text reports a lost cell with its counters) and H1's wild m = 10 against the
    ablation arm (the cross-round note)."""
    want = {("param-last", 1000): ("regexmatcher-v2", "regexmatcher-v2-ct"),
            ("wild", 10): ("regexmatcher-v2", "regexmatcher-v2-r1")}
    rows: dict = {}
    with (run / "cells.jsonl").open(encoding="utf-8") as f:
        for line in f:
            if '"regexmatcher-v2' not in line:
                continue
            d = json.loads(line)
            key = (d["shape"], d["m"])
            if key in want and d["arm"] in want[key]:
                rows.setdefault(key, {}).setdefault(d["table_seed"], {})[d["arm"]] = d
    for key, (base, other) in want.items():
        per = rows[key]
        check(len(per) == 16 and all(len(v) == 2 for v in per.values()), f"sixteen pairs of {key}")
        ratios = {s: v[other]["ns_median"] / v[base]["ns_median"] for s, v in per.items()}
        if key == ("param-last", 1000):
            seed = max(ratios, key=ratios.get)
            v = per[seed]
            check(abs(v[other]["instructions"] - v[base]["instructions"]) < 0.5, "equal instructions in the slow pair")
            mc.add("HSevenLostSeed", str(seed))
            mc.add("HSevenLostSeedCyclesCt", fixed(v[other]["cycles"], 1))
            mc.add("HSevenLostSeedCyclesRt", fixed(v[base]["cycles"], 1))
            mc.add("HSevenLostSeedInsn", fixed(v[base]["instructions"], 1))
            others = sorted(r for s, r in ratios.items() if s != seed)
            mc.add("HSevenLostOthersMax", ratio(others[-1]))
            mc.add("HSevenLostAboveMargin", count(sum(r >= 1.02 for r in ratios.values())))
            mc.add("HSevenLostAboveOne", count(sum(r > 1.0 for r in ratios.values())))
        else:
            ratios = {s: v[base]["ns_median"] / v[other]["ns_median"] for s, v in per.items()}
            seed = max(ratios, key=ratios.get)
            v = per[seed]
            check(abs(v[other]["instructions"] - v[base]["instructions"]) < 0.5, "equal instructions, wild 10")
            check(all(abs(x[other]["instructions"] - x[base]["instructions"]) < 0.5 for x in per.values()),
                  "v2 and the ablation arm run equal instructions in every pair of wild m = 10")
            mc.add("WildTenSlowSeed", str(seed))
            mc.add("WildTenSlowRatio", ratio(ratios[seed]))
            mc.add("WildTenSlowCyclesVtwo", fixed(v[base]["cycles"], 1))
            mc.add("WildTenSlowCyclesAb", fixed(v[other]["cycles"], 1))
            others = sorted(r for s, r in ratios.items() if s != seed)
            mc.add("WildTenOthersMin", ratio(others[0]))
            mc.add("WildTenOthersMax", ratio(others[-1]))


