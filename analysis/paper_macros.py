def render(results: Path, run: Path) -> str:
    s = json.loads((results / "summary.json").read_text(encoding="utf-8"))
    mc = Macros()
    versions(mc)
    provenance(mc, s, run)
    design(mc, s, run)
    run_counts(mc, results, run)
    h1(mc, s, results)
    h2(mc, s, results)
    h3(mc, s)
    h4(mc, s, results)
    h5(mc, s, results)
    h6(mc, s, results, run)
    h7(mc, s, results)
    h7_costs(mc, results)
    explore(mc, results)
    ablation(mc, s, results)
    pair_details(mc, run)
    ct_heap(mc, results)
    archives(mc)
    explore_archives(mc)
    coverage_gap(mc)
    return HEAD + mc.text()


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--results", type=Path, default=PAPER / "results/round2")
    ap.add_argument("--run", type=Path, default=Path("D:/Archive/p2-raw/runs/2026-09-30-L-publication"),
                    help="the unpacked main grid (toolchain.txt, cells.jsonl, verified*.jsonl)")
    ap.add_argument("--out", type=Path)
    a = ap.parse_args()
    if a.results.resolve() == (PAPER / "results").resolve():
        raise SystemExit("paper_macros: results/ is round 1; give results/round2")
    text = render(a.results, a.run)
    if a.out:
        a.out.write_text(text, encoding="utf-8", newline="\n")
    else:
        print(text, end="")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
