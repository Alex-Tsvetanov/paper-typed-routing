#!/usr/bin/env python3
"""The paper's two figures, as pgfplots pictures, from the files the macros come from.

    python t3/paper_figures.py [--summary results/round2/summary.json] [--design design/round3]
                         [--plan t3/plans/rr-W.json] [--out results/round3/figures]

lookup-ratio.tex: the earlier campaign's lookup grid. One panel per table shape; x is the table size m (log scale),
y the median over the seed pairs of v2's lookup time divided by the fastest competitor's, with its interval (the
clustered BCa bounds of summary.json); a solid line at 1 and a dashed line at the margin. Same values and rounding
as analysis/macros.py's \\HOneRatio*, \\HOneLow* and \\HOneHigh*.

e2e-lead.tex: this study's end-to-end campaign. One panel per system and size; for each program, v2's lead over the
next router (the floor's first neighbour pair), the A/A floor (the A/A run's largest |d|) and the span of the
k-server run's medians, in ns per request. Same values and rounding as t3/rr_macros.py's \\RThree*Lead, *Floor and
*KSpan.

Nothing is typed by hand. A value that is missing (a floor without a counted A/A pair, a span of one value) is
left out of its panel and named in a comment of the file. Each file needs pgfplots with the groupplots library;
lookup-ratio.tex also needs \\shape and e2e-lead.tex \\RThreeKCopies, both defined where the manuscript reads the
macros.
"""
from __future__ import annotations

import argparse
import json
import sys
from decimal import Decimal
from pathlib import Path

HERE = Path(__file__).resolve().parent
ROOT = HERE.parent
sys.path.insert(0, str(ROOT / "analysis"))
sys.path.insert(0, str(HERE))
from macros_util import count, nanoseconds, ratio  # noqa: E402
from rr_macros import PROGRAMS, SYSTEMS, cell_of  # noqa: E402

SHAPES = ("static", "param-last", "param-first", "rest", "wild", "mixed-disjoint", "mixed-overlap")
SYSTEM_TEXT = {"linux": "Linux", "windows": "Windows on the same laptop"}
RATIO_YMAX = Decimal("1.2")
X_MIN, X_MAX = 5, 200000


def plain(s: str) -> str:
    """A macro's number as a pgfplots coordinate: no digit grouping, an ASCII minus."""
    return s.replace("{,}", "").replace("\\ensuremath{-}", "-")


def lookup_rows(summary: dict) -> dict[str, list[tuple[int, str, str, str]]]:
    """Per shape, (m, ratio, low, high) of every tested cell, as the macros print them."""
    rows: dict[str, list[tuple[int, str, str, str]]] = {s: [] for s in SHAPES}
    for r in summary["h1_cells"]:
        if r.get("status") != "tested":
            continue
        if r["shape"] not in rows:
            raise ValueError(f"unknown shape {r['shape']}")
        rows[r["shape"]].append((int(r["m"]), ratio(r["ratio"]), ratio(r["ci_low"]), ratio(r["ci_high"])))
    for shape, cells in rows.items():
        cells.sort()
        if not cells:
            raise ValueError(f"no tested cell for {shape}")
    return rows


def lookup_figure(summary: dict) -> str:
    rows = lookup_rows(summary)
    margin = ratio(summary["h1"]["margin"])
    top = max([Decimal(h) for cells in rows.values() for _, _, _, h in cells] + [Decimal(margin)])
    if top >= RATIO_YMAX:
        raise ValueError(f"an upper bound {top} reaches the figure's top {RATIO_YMAX}")
    sizes = sorted({m for cells in rows.values() for m, *_ in cells})
    out = [
        "% Generated by t3/paper_figures.py from results/round2/summary.json. Do not edit.",
        "% Needs pgfplots with \\usepgfplotslibrary{groupplots}, and \\shape (defined with the manuscript's macros).",
        "% Per panel (a table shape): x, the table size m in routes (log scale); y, the median over the seed pairs of",
        "% the matcher's lookup time divided by the fastest competitor's, with its interval; solid line 1, dashed",
        f"% line the margin {margin}.",
        "\\begin{tikzpicture}",
        "\\begin{groupplot}[group style={group size=4 by 2, horizontal sep=0.9cm, vertical sep=1.5cm},",
        f"  width=4.3cm, height=3.6cm, xmode=log, xmin={X_MIN}, xmax={X_MAX}, ymin=0, ymax={RATIO_YMAX},",
        f"  xtick={{{','.join(str(m) for m in sizes)}}}, ytick={{0,0.5,1}},",
        "  tick label style={font=\\scriptsize}, title style={font=\\small}]",
    ]
    for shape in SHAPES:
        out.append(f"\\nextgroupplot[title={{\\shape{{{shape}}}}}]")
        out.append(f"\\addplot[gray, thin, forget plot] coordinates {{({X_MIN},1) ({X_MAX},1)}};")
        out.append(f"\\addplot[black, thin, dashed, forget plot] coordinates {{({X_MIN},{margin}) ({X_MAX},{margin})}};")
        out.append("\\addplot[black, mark=*, mark size=1.2pt, error bars/.cd, y dir=both, y explicit] coordinates {")
        for m, r, lo, hi in rows[shape]:
            plus, minus = Decimal(hi) - Decimal(r), Decimal(r) - Decimal(lo)
            if plus < 0 or minus < 0:
                raise ValueError(f"{shape} m={m}: the interval [{lo}, {hi}] does not hold the ratio {r}")
            out.append(f"  ({m},{r}) += (0,{plus}) -= (0,{minus})")
        out.append("};")
    out += ["\\end{groupplot}", "\\end{tikzpicture}", ""]
    return "\n".join(out)


def e2e_rows(systems: dict, sizes: list[int]) -> dict[tuple[str, int], list[tuple[str, str | None, str | None, str | None]]]:
    """Per (system, m), per program: (program word, lead, floor, k-span) as the macros print them; None if missing."""
    out = {}
    for system, _, _ in SYSTEMS:
        an = systems[system]
        for m in sizes:
            cell = cell_of(m)
            rows = []
            for program, pword, _ in PROGRAMS:
                floor = an["floor"][cell][program]
                lead = floor["neighbours"][0]
                if lead["ahead"] != "v2":
                    raise ValueError(f"{system} {program} m={m}: the floor's first pair is not v2's lead")
                span = an["aak"]["cells"][cell]["programs"][program]["medians_ns"].get("range")
                rows.append((pword, *(None if x is None else plain(nanoseconds(x))
                                      for x in (lead["gap_ns"], floor["aa_largest_abs_d_ns"], span))))
            out[(system, m)] = rows
    return out


def e2e_figure(systems: dict, sizes: list[int]) -> str:
    rows = e2e_rows(systems, sizes)
    words = [pword for _, pword, _ in PROGRAMS]
    out = [
        "% Generated by t3/paper_figures.py from design/round3/floor-L.json and floor-W.json. Do not edit.",
        "% Needs pgfplots with \\usepgfplotslibrary{groupplots}, and \\RThreeKCopies (from the manuscript's macros).",
        "% Per panel (a system and a table size m): per program, the matcher's lead over the next router, the A/A",
        "% floor, and the span of the medians of the separate processes of the matcher, in ns per request.",
    ]
    missing = [f"{SYSTEM_TEXT[s]}, m={m}, {pword}: {what}" for (s, m), prog in rows.items()
               for pword, *vals in prog for what, v in zip(("lead", "floor", "span"), vals) if v is None]
    out += [f"% Left out (missing): {x}." for x in missing]
    if any(Decimal(v) <= 0 for prog in rows.values() for _, *vals in prog for v in vals if v is not None):
        raise ValueError("a value is not positive, so it has no place on the figure's log scale")
    out += [
        "\\begin{tikzpicture}",
        f"\\begin{{groupplot}}[group style={{group size={len(sizes)} by {len(SYSTEMS)}, horizontal sep=1.6cm,"
        " vertical sep=1.9cm},",
        "  width=6.2cm, height=4.2cm, ymode=log, enlarge x limits=0.3, log ticks with fixed point,",
        "  ytick={10,20,50,100,200,500,1000,2000,5000}, minor ytick={},",
        f"  symbolic x coords={{{','.join(words)}}}, xtick=data,"
        f" xticklabels={{{','.join(text for _, _, text in PROGRAMS)}}},",
        "  ylabel={ns per request (log scale)}, tick label style={font=\\scriptsize}, label style={font=\\small},",
        "  title style={font=\\small, align=center}]",
    ]
    styles = ("only marks, mark=*, mark size=2pt, black, xshift=-6pt",
              "only marks, mark=square*, mark size=1.8pt, gray, xshift=0pt",
              "only marks, mark=triangle, mark size=2.4pt, black, xshift=6pt")
    first = True
    for system, _, _ in SYSTEMS:
        for m in sizes:
            opts = f"title={{{SYSTEM_TEXT[system]}\\\\$m={count(m)}$}}"
            if first:
                opts += (", legend style={at={(0,1.38)}, anchor=south west, legend columns=3,"
                         " font=\\scriptsize, draw=none}")
            out.append(f"\\nextgroupplot[{opts}]")
            for k, style in enumerate(styles):
                points = " ".join(f"({pword},{vals[k]})" for pword, *vals in rows[(system, m)] if vals[k] is not None)
                out.append(f"\\addplot[{style}] coordinates {{{points}}};")
            if first:
                out.append("\\legend{the matcher's lead over the next router, the A/A floor,"
                           " span over \\RThreeKCopies\\ processes of the matcher}")
                first = False
    out += ["\\end{groupplot}", "\\end{tikzpicture}", ""]
    return "\n".join(out)


def generate(summary_path: Path, design: Path, plan_path: Path) -> dict[str, str]:
    summary = json.loads(summary_path.read_text(encoding="utf-8"))
    sizes = json.loads(plan_path.read_text(encoding="utf-8"))["sizes"]
    systems = {system: json.loads((design / f"floor-{letter}.json").read_text(encoding="utf-8"))
               ["analysis"]["systems"][system] for system, _, letter in SYSTEMS}
    return {"lookup-ratio.tex": lookup_figure(summary), "e2e-lead.tex": e2e_figure(systems, sizes)}


def main(argv: list[str] | None = None) -> int:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--summary", type=Path, default=ROOT / "results" / "round2" / "summary.json")
    ap.add_argument("--design", type=Path, default=ROOT / "design" / "round3")
    ap.add_argument("--plan", type=Path, default=HERE / "plans" / "rr-W.json")
    ap.add_argument("--out", type=Path, default=ROOT / "results" / "round3" / "figures")
    a = ap.parse_args(argv)
    figures = generate(a.summary, a.design, a.plan)
    a.out.mkdir(parents=True, exist_ok=True)
    for name, text in figures.items():
        (a.out / name).write_text(text, encoding="utf-8", newline="\n")
    return 0


if __name__ == "__main__":
    sys.exit(main())
