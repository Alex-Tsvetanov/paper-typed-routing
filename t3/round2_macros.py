#!/usr/bin/env python3
"""Round 2's paper macros without the desktop's numbers, for the writing pack.

    python t3/round2_macros.py [--src results/round2/macros-paper.tex] [--out results/round3/round2-paper-macros.tex]

Round 2 measured H7's MSVC costs on the desktop (W before 2026-10-23), and desktop data never appears as a result
(CLAUDE.md, Hosts); they are measured again on the laptop's Windows (t3/jobs/ctmsvc.py). This copies
results/round2/macros-paper.tex line by line and leaves out every macro that holds a desktop number or names the
desktop: DESKTOP below. The four cost rows (CostRowTen, CostRowHundred, CostRowThousand, CostRowGithub) hold
Linux's clang columns and then the desktop's MSVC columns; each becomes CostRowClang<size> with its first
CLANG_COLUMNS columns only, the values round 2's analysis/paper_macros.py wrote, unchanged. results/round2/macros.tex
holds no desktop number and is pulled as it is.
"""
from __future__ import annotations

import argparse
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
DESKTOP = {"MsvcVersion", "HostWCpu", "HostWArch", "MsvcTables", "MsvcCrashSteps", "MsvcBudgetFailSteps",
           "MsvcPeakMaxGB", "MsvcPeakMinGB", "MsvcPeakMinMiB", "MsvcPeakMaxMiB", "ArchiveMsvc", "ArchiveMsvcSha"}
COST_ROWS = {"CostRowTen": "CostRowClangTen", "CostRowHundred": "CostRowClangHundred",
             "CostRowThousand": "CostRowClangThousand", "CostRowGithub": "CostRowClangGithub"}
CLANG_COLUMNS = 5   # size, tables, compile s, object bytes, clang's steps (analysis/paper_macros.py, h7_costs)
LINE = re.compile(r"^\\newcommand\{\\([A-Za-z]+)\}\{(.*)\}(  % .*)?$")


def convert(src: str) -> str:
    out = ["% Generated by t3/round2_macros.py from results/round2/macros-paper.tex: round 2's paper macros without",
           "% the desktop's numbers (its MSVC costs and its CPU); the cost rows keep Linux's clang columns. Do not edit."]
    seen = set()
    for line in src.splitlines():
        m = LINE.match(line)
        if not m:
            if line.startswith("\\newcommand"):
                raise ValueError(f"a macro line not understood: {line[:80]}")
            continue   # round 2's header comment
        name, value = m.group(1), m.group(2)
        seen.add(name)
        if name in DESKTOP:
            continue
        if name in COST_ROWS:
            cols = value.split(" & ")
            if len(cols) != CLANG_COLUMNS + 3:
                raise ValueError(f"{name} has {len(cols)} columns, not {CLANG_COLUMNS} clang and 3 MSVC")
            out.append(f"\\newcommand{{\\{COST_ROWS[name]}}}{{{' & '.join(cols[:CLANG_COLUMNS])}}}"
                       "  % Linux's clang columns of " + name)
            continue
        out.append(line)
    missing = (DESKTOP | set(COST_ROWS)) - seen
    if missing:
        raise ValueError(f"not in the source: {sorted(missing)}")
    return "\n".join(out) + "\n"


def main(argv: list[str] | None = None) -> int:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--src", type=Path, default=ROOT / "results" / "round2" / "macros-paper.tex")
    ap.add_argument("--out", type=Path, default=ROOT / "results" / "round3" / "round2-paper-macros.tex")
    a = ap.parse_args(argv)
    a.out.write_text(convert(a.src.read_text(encoding="utf-8")), encoding="utf-8", newline="\n")
    return 0


if __name__ == "__main__":
    sys.exit(main())
