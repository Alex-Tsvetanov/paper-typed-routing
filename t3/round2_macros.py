#!/usr/bin/env python3
"""Round 2's paper macros without the desktop's numbers, for the writing pack.

    python t3/round2_macros.py [--src results/round2/macros-paper.tex] [--out results/round3/round2-paper-macros.tex]

Round 2 measured H7's MSVC costs on the desktop (W before 2026-10-23), and desktop data never appears as a result
(CLAUDE.md, Hosts); they are measured again on the laptop's Windows (t3/jobs/ctmsvc.py). This copies
results/round2/macros-paper.tex line by line and leaves out every macro that holds a desktop number or names the
desktop: DESKTOP below. The four cost rows (CostRowTen, CostRowHundred, CostRowThousand, CostRowGithub) hold
Linux's clang columns and then the desktop's MSVC columns; each becomes CostRowClang<size> with its first
CLANG_COLUMNS columns only, the values round 2's analysis/paper_macros.py wrote, unchanged. results/round2/macros.tex
holds no desktop number and is pulled as it is.

It adds H5(c)'s evidence, which round 2's analysis checks but writes no macro for: hypotheses-round2.md says (c)'s
tests are in the minimal server's suite and their evidence is the server's sanitizer records. From
lab/sanitizer-records/mserver-f626955eb-L-{asan,tsan,msan}.json (the records analysis/paper_macros.py reads):
HFiveCRecords, the records; HFiveCTests and HFiveCFailed, the server suite's tests and failures as each record's
ctest preset states them (they must agree); HFiveCVerdict, "holds" when every record is green with CTest exit 0, no
sanitizer report and no failed test, else "does not hold".
"""
from __future__ import annotations

import argparse
import json
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
DESKTOP = {"MsvcVersion", "HostWCpu", "HostWArch", "MsvcTables", "MsvcCrashSteps", "MsvcBudgetFailSteps",
           "MsvcPeakMaxGB", "MsvcPeakMinGB", "MsvcPeakMinMiB", "MsvcPeakMaxMiB", "ArchiveMsvc", "ArchiveMsvcSha"}
COST_ROWS = {"CostRowTen": "CostRowClangTen", "CostRowHundred": "CostRowClangHundred",
             "CostRowThousand": "CostRowClangThousand", "CostRowGithub": "CostRowClangGithub"}
CLANG_COLUMNS = 5   # size, tables, compile s, object bytes, clang's steps (analysis/paper_macros.py, h7_costs)
LINE = re.compile(r"^\\newcommand\{\\([A-Za-z]+)\}\{(.*)\}(  % .*)?$")
SANITIZERS = ("asan", "tsan", "msan")
SERVER_RECORD = "mserver-f626955eb-L-{san}.json"
CTEST = re.compile(r"^exit (\d+), (\d+) tests, (\d+) failed$")


def server_evidence(records: Path) -> list[str]:
    """H5(c)'s macros from the minimal server's records (see the docstring)."""
    seen, ok = set(), True
    for san in SANITIZERS:
        rec = json.loads((records / SERVER_RECORD.format(san=san)).read_text(encoding="utf-8"))
        (ctest,) = [p for p in rec["presets"] if p["preset"] == "ctest"]
        m = CTEST.match(ctest["detail"])
        if not m:
            raise ValueError(f"{san}: the ctest preset says {ctest['detail']!r}")
        exit_code, tests, failed = map(int, m.groups())
        seen.add((tests, failed))
        ok &= (rec["green"] and rec["ctest_exit"] == 0 and exit_code == 0 and failed == 0
               and rec["sanitizer_reports"] == 0)
    if len(seen) != 1:
        raise ValueError(f"the server's records disagree on the suite: {sorted(seen)}")
    (tests, failed), = seen
    note = "  % lab/sanitizer-records/" + SERVER_RECORD.format(san="{asan,tsan,msan}")
    return [f"\\newcommand{{\\HFiveCRecords}}{{{len(SANITIZERS)}}}" + note,
            f"\\newcommand{{\\HFiveCTests}}{{{tests}}}  % the minimal server's CTest suite, as each record states it",
            f"\\newcommand{{\\HFiveCFailed}}{{{failed}}}",
            f"\\newcommand{{\\HFiveCVerdict}}{{{'holds' if ok else 'does not hold'}}}"]


def convert(src: str, records: Path | None = None) -> str:
    out = ["% Generated by t3/round2_macros.py from results/round2/macros-paper.tex: round 2's paper macros without",
           "% the desktop's numbers (its MSVC costs and its CPU); the cost rows keep Linux's clang columns. Do not edit."]
    seen = set()
    for line in src.splitlines():
        m = LINE.match(line)
        if not m:
            if line.startswith("\\newcommand"):
                raise ValueError(f"a macro line not understood: {line[:80]}")
            continue   # round 2's header comment
        name, value = m.group(1), m.group(2)
        seen.add(name)
        if name in DESKTOP:
            continue
        if name in COST_ROWS:
            cols = value.split(" & ")
            if len(cols) != CLANG_COLUMNS + 3:
                raise ValueError(f"{name} has {len(cols)} columns, not {CLANG_COLUMNS} clang and 3 MSVC")
            out.append(f"\\newcommand{{\\{COST_ROWS[name]}}}{{{' & '.join(cols[:CLANG_COLUMNS])}}}"
                       "  % Linux's clang columns of " + name)
            continue
        out.append(line)
    missing = (DESKTOP | set(COST_ROWS)) - seen
    if missing:
        raise ValueError(f"not in the source: {sorted(missing)}")
    if records is not None:
        out += server_evidence(records)
    return "\n".join(out) + "\n"


def main(argv: list[str] | None = None) -> int:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--src", type=Path, default=ROOT / "results" / "round2" / "macros-paper.tex")
    ap.add_argument("--out", type=Path, default=ROOT / "results" / "round3" / "round2-paper-macros.tex")
    ap.add_argument("--records", type=Path, default=ROOT / "lab" / "sanitizer-records")
    a = ap.parse_args(argv)
    a.out.write_text(convert(a.src.read_text(encoding="utf-8"), a.records), encoding="utf-8", newline="\n")
    return 0


if __name__ == "__main__":
    sys.exit(main())
