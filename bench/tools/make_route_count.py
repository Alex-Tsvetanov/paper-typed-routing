#!/usr/bin/env python3
"""Write, or check, the counting copy of RegexMatcher v2's route headers (tools/route_count.hpp), the
untimed half of the adversarial tool (tools/adversarial.cpp, design/review-runs/adversarial.md).

    make_route_count.py --regexmatcher DIR [--out tools/route_count.hpp]
    make_route_count.py --regexmatcher DIR --check [--out tools/route_count.hpp]

DIR is a RegexMatcher checkout or snapshot at the pinned commit (d1d73e99b). The copy is the five
headers the walk needs (config, detail/words, pattern, table, lookup, in that order) with their
own includes dropped and the standard ones gathered at the top, renamed to the namespace
matcher::route_count and the macro prefix MATCHER_ROUTE_COUNT_, plus the counting hook: one
struct (Counter), its pointer, one macro, and seven lines in detail::walk, each anchored on a line
of the pinned walk and marked "counting". --check writes nothing and exits 1 if the file on disk
differs from what DIR gives (CRLF read as LF), so a test can show that the copy is the pinned
code and the hook, and nothing else.
"""

from __future__ import annotations

import argparse
import re
import sys
from pathlib import Path

HEADERS = ("config.hpp", "detail/words.hpp", "pattern.hpp", "table.hpp", "lookup.hpp")
OUT = Path(__file__).resolve().parent / "route_count.hpp"

PREAMBLE = """\
// The counting copy of the adversarial tool (tools/adversarial.cpp, design/review-runs/adversarial.md):
// RegexMatcher v2's route headers at d1d73e99b (include/matcher/route/config.hpp, detail/words.hpp,
// pattern.hpp, table.hpp and lookup.hpp, in that order) copied under the namespace matcher::route_count
// and the macro prefix MATCHER_ROUTE_COUNT_, so that it links beside the pinned headers in one binary.
// Generated by tools/make_route_count.py, which also checks it against the pinned headers (--check).
//
// The only change is a hook. The trie walk (detail::walk) calls route_count::counter, when it is set
// and only at run time, in seven added lines marked "counting": once per walk (its root), at every
// pass of the walk's loop (the node and the stage: stage 0 enters the node, a higher stage resumes it
// after a pop), after each of the four pushes of a choice point and after the pop (the node and the
// stack's depth after it). The walk's decisions, the build and the rest of the lookup are v2's. The
// timed lookups use the pinned headers, never this copy.
#pragma once
"""

HOOK = """\
namespace matcher::route_count
{

	// counting: what the walk reports, at run time only (MATCHER_ROUTE_COUNT_HOOK).
	struct Counter
	{
		virtual void walk(std::uint32_t root) noexcept = 0;
		virtual void visit(std::uint32_t node, std::uint8_t stage) noexcept = 0;
		virtual void push(std::uint32_t node, std::size_t depth) noexcept = 0;
		virtual void pop(std::uint32_t node, std::size_t depth) noexcept = 0;

	protected:
		~Counter() = default;
	};

	inline Counter* counter = nullptr;

}  // namespace matcher::route_count

#define MATCHER_ROUTE_COUNT_HOOK(call)                  \\
	do                                                  \\
	{                                                   \\
		if !consteval                                   \\
		{                                               \\
			if (::matcher::route_count::counter)        \\
			{                                           \\
				::matcher::route_count::counter->call; \\
			}                                           \\
		}                                               \\
	} while (false)
"""

# (anchor line, line inserted after it, how many times the anchor occurs in the pinned walk)
INSERTS = (
    ("\t\t\tconst std::size_t len = path.size();", "\t\t\tMATCHER_ROUTE_COUNT_HOOK(walk(root));  // counting", 1),
    ("\t\t\t\tconst Node& n = t.nodes[node];", "\t\t\t\tMATCHER_ROUTE_COUNT_HOOK(visit(node, stage));  // counting", 1),
    ("\t\t\t\t\t\t\t\tstack[sp++] = {node, static_cast<std::uint32_t>(pos), nv, 1};",
     "\t\t\t\t\t\t\t\tMATCHER_ROUTE_COUNT_HOOK(push(node, sp));  // counting", 1),
    ("\t\t\t\t\t\t\t\tstack[sp++] = {node, static_cast<std::uint32_t>(pos), nv, 2};",
     "\t\t\t\t\t\t\t\tMATCHER_ROUTE_COUNT_HOOK(push(node, sp));  // counting", 1),
    ("\t\t\t\t\t\t\t\tstack[sp++] = {node, static_cast<std::uint32_t>(pos), nv, 3};",
     "\t\t\t\t\t\t\t\tMATCHER_ROUTE_COUNT_HOOK(push(node, sp));  // counting", 1),
    ("\t\t\t\t\t\t\t\tstack[sp++] = {node, static_cast<std::uint32_t>(pos), nv, 4};",
     "\t\t\t\t\t\t\t\tMATCHER_ROUTE_COUNT_HOOK(push(node, sp));  // counting", 1),
    ("\t\t\t\tconst Choice c = stack[--sp];", "\t\t\t\tMATCHER_ROUTE_COUNT_HOOK(pop(c.node, sp));  // counting", 1),
)

INCLUDE = re.compile(r"^#include\s+(<[^>]+>|\"[^\"]+\")\s*$")


def read(path: Path) -> str:
    return path.read_bytes().decode("utf-8").replace("\r\n", "\n")


def rename(text: str) -> str:
    text = text.replace("namespace matcher::route\n", "namespace matcher::route_count\n")
    text = text.replace("}  // namespace matcher::route\n", "}  // namespace matcher::route_count\n")
    return text.replace("MATCHER_ROUTE_", "MATCHER_ROUTE_COUNT_")


def generate(root: Path) -> str:
    base = root / "include" / "matcher" / "route"
    includes: list[str] = []
    bodies: list[str] = []
    for name in HEADERS:
        lines = []
        for line in read(base / name).split("\n"):
            m = INCLUDE.match(line)
            if line.strip() == "#pragma once":
                continue
            if m:
                if not m.group(1).startswith("<matcher/") and line not in includes:
                    includes.append(line)
                continue
            lines.append(line)
        body = "\n".join(lines).strip("\n")
        body = re.sub(r"\n{3,}", "\n\n", body)
        if "namespace matcher::route\n" not in body + "\n":
            raise SystemExit(f"make_route_count: {name} has no namespace matcher::route")
        bodies.append(rename(body + "\n"))
    # The hook follows config.hpp's limits and precedes the headers whose walk calls it.
    text = (PREAMBLE + "\n" + "\n".join(sorted(includes)) + "\n\n" + bodies[0] + "\n" + HOOK + "\n"
            + "\n".join(bodies[1:]))
    for anchor, added, times in INSERTS:
        found = text.count(anchor + "\n")
        if found != times:
            raise SystemExit(f"make_route_count: the anchor {anchor.strip()!r} occurs {found} times, not {times}")
        text = text.replace(anchor + "\n", anchor + "\n" + added + "\n")
    return text


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--regexmatcher", type=Path, required=True, help="RegexMatcher at the pinned commit")
    ap.add_argument("--out", type=Path, default=OUT)
    ap.add_argument("--check", action="store_true", help="compare with the file on disk; write nothing")
    args = ap.parse_args()
    text = generate(args.regexmatcher)
    if args.check:
        same = args.out.exists() and read(args.out) == text
        print(f"make_route_count: {args.out.name} {'is' if same else 'is NOT'} the pinned headers and the hook")
        return 0 if same else 1
    args.out.write_bytes(text.encode("utf-8"))
    print(f"make_route_count: wrote {args.out}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
